# ==========================================================
# Multi-Source Land Cover Classification Pipeline using sits
# ==========================================================

# This script follows the cube generation workflow (1_CubeCreation.R).
#
# It uses multi-source Earth observation data to prepare training
# samples, train several machine-learning and deep-learning models,
# and produce land-cover classification maps.
#
# The main workflow is divided into the following steps:
#
# 1. Loads pre-processed and regularized Earth observation cubes
# 2. Merges the different Earth observation datasets
# 3. Prepares, assesses, cleans, and balances the training samples
# 4. Trains a Random Forest model and generates a probability cube
# 5. Trains a Temporal Convolutional Neural Network (TempCNN),
#    generates a probability cube, applies spatial smoothing,
#    and produces a final classification map
# 6. Trains an XGBoost model, generates a probability cube,
#    applies spatial smoothing, and produces a final classification map
# 7. Trains a Multilayer Perceptron (MLP) model and generates
#    a probability cube
#
# The probability cubes generated by the different models can
# subsequently be used for comparison and ensemble analyses.
#
# The spatial smoothing parameters used for classifications are based on the 95th percentile
# of the estimated logit variance distribution.
#
# IMPORTANT:
# The input data are not included in this repository.
# The paths defined in Section 0.1 must therefore be adapted
# to the local data and computing environment before running
# the script.

# ==========================================================

